package com.pushledger.ui

import androidx.compose.ui.text.font.Font
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.unit.sp
import com.pushledger.R

/**
 * 이 앱의 유일한 글꼴. 갈무리11 — 11픽셀로 설계된 픽셀 폰트다.
 *
 * 한글을 도트로 찍으려고 직접 만들어 봤다. 낱자를 조합하는 대신 시스템 폰트를 작게
 * 그려 격자로 읽어 냈는데, 그렇게 나온 글자는 읽을 수는 있어도 볼 만하지 않았다.
 * 획 굵기가 제멋대로고 받침이 붙었다.
 *
 * 한글 11,172자를 사람이 하나씩 그려 둔 폰트를 쓰는 편이 낫다. 그게 이 폰트다.
 * 조합해 만드는 게 아니라 글자마다 그려져 있어서 받침이 있어도 뭉개지지 않는다.
 * 라이선스는 OFL 1.1 (저장소 루트 LICENSE-Galmuri.md).
 *
 * 11픽셀의 정수 배가 되는 크기에서 픽셀이 정확히 떨어진다. 그래서 큰 글자 두 단은
 * 배수에 맞춰 뒀다 — 화면에서 제일 크게 보이는 숫자라 흐려지면 바로 티가 난다.
 */
val Pixel = FontFamily(Font(R.font.galmuri11))

/**
 * 글자 크기는 이 다섯 단이 전부다.
 *
 * 정비 전에는 9sp 부터 30sp 까지 열세 가지가 163곳에 흩어져 있었다.
 * 1sp 차이는 눈에 띄지 않지만 같은 줄에 섞이면 기준선이 미세하게 어긋나고,
 * 그 어긋남이 쌓여 화면이 흐려 보인다.
 *
 * 새 화면을 만들 때 크기를 고민하지 않는 것이 이 목록의 목적이다.
 * 여기 없는 크기가 필요하다고 느껴지면 대개는 크기가 아니라 위계가 잘못된 것이다.
 */
object T {
    /** 화면을 대표하는 숫자 하나. 홈의 남은 예산, 통계의 총 지출. 11의 9배. */
    val Display = 33.sp

    /** 카드 안에서 가장 큰 숫자. 오늘 가용 예산, 타일 금액. 11의 6배. */
    val Amount = 22.sp

    /** 항목 이름, 다이얼로그 제목. 읽는 사람이 무엇인지 먼저 아는 자리. */
    val Title = 15.sp

    /** 본문과 목록 줄. 화면에서 가장 많이 쓰인다. */
    val Body = 13.sp

    /** 보조 설명, 축 라벨, 배지. 없어도 뜻이 통해야 하는 글자. */
    val Caption = 11.sp
}

/**
 * 입력칸 전용 크기. 읽는 단계([T])와 따로 둔다.
 *
 * 읽기와 쓰기는 요구가 다르다. 손으로 치는 자리는 커서가 어디 있는지 보여야 해서
 * 같은 위계의 읽기 글자보다 한 치수 크다. 그 차이를 [T] 에 섞으면 다섯 단이
 * 여덟 단이 되고, "여기 없는 크기가 필요하면 위계가 잘못된 것" 이라는 기준이 무너진다.
 *
 * 값은 `Field.kt` 에 흩어져 있던 것을 그대로 옮겨 온 것이다 — 화면은 안 바뀐다.
 * 흩어져 있으면 입력칸 크기를 손볼 때 어디를 고쳐야 하는지 알 수 없었다.
 */
object TField {
    /** 금액 입력칸. 화면에서 가장 크게 치는 자리라 굵게 같이 쓴다. */
    val Big = 17.sp

    /** 보통 입력칸. */
    val Normal = 14.sp

    /** 입력칸 뒤에 붙는 단위("원", "일"). */
    val Small = 12.sp
}
