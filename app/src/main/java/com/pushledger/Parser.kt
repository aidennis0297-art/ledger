                "매머드", "메머드",
                "반찬", "반찬가게", "식자재", "김치", "채소"
            ) -> Cat.FOOD

            // 2. 고정지출 (월세, 관리비, 공과금, 통신비)
            has(
                "월세", "임대료", "관리비", "선수관리비", "아파트관리비", "빌라관리비",
                "전기요금", "한국전력", "한전", "도시가스", "가스비", "삼천리", "수도요금", "상하수도", "난방비", "공과금", "지로",
